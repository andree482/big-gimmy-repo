// Funzione per ottenere il percorso dell'immagine
export function getProductImage(slug: string): string {
  // Prima controlla la mappatura specifica
  if (imageMapping[slug]) {
    return imageMapping[slug];
  }
  
  // Fallback per prodotti non mappati - usa un'immagine generica
  return "/assets/placeholder-product.jpg";
}

// Funzione per creare un'immagine placeholder se necessario
export function createProductImages(slug: string, name: string) {
  const imagePath = getProductImage(slug);
  return [{
    src: imagePath,
    alt: name
  }];
}